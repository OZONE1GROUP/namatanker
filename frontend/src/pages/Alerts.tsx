import { useEffect, useState } from "react"
import { useNavigate, useSearchParams } from "react-router-dom"
import { Loader2, Check, CheckCheck, ArrowUpCircle } from "lucide-react"
import { getAlerts, alertActions, ApiError, type AlertListItem } from "@/lib/api"
import { Card } from "@/components/ui/Card"
import { StatusBadge } from "@/components/ui/Badge"
import { Button } from "@/components/ui/Button"
import { statusTone, prettyStatus } from "@/lib/orderStatus"
import { formatDateTime, formatNumber } from "@/lib/utils"

const SEVERITIES = ["info", "warning", "critical"]
const STATUSES = ["open", "acknowledged", "resolved", "escalated"]

export function Alerts() {
  const navigate = useNavigate()
  const [params, setParams] = useSearchParams()
  const [data, setData] = useState<{ items: AlertListItem[]; total: number } | null>(null)
  const [loading, setLoading] = useState(true)
  const [busyId, setBusyId] = useState<string | null>(null)
  const [error, setError] = useState<string | null>(null)

  const status = params.get("status") ?? ""
  const severity = params.get("severity") ?? ""

  function load() {
    setLoading(true)
    getAlerts({ status: status || undefined, severity: severity || undefined, page: 1, page_size: 100 })
      .then(setData)
      .finally(() => setLoading(false))
  }

  useEffect(load, [status, severity])

  function updateFilter(key: string, value: string) {
    const next = new URLSearchParams(params)
    if (value) next.set(key, value)
    else next.delete(key)
    setParams(next)
  }

  async function runAction(id: string, action: "acknowledge" | "resolve" | "escalate") {
    setBusyId(id)
    setError(null)
    try {
      await alertActions[action](id)
      load()
    } catch (e) {
      setError(e instanceof ApiError ? e.message : "Action failed")
    } finally {
      setBusyId(null)
    }
  }

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <p className="text-sm text-(--app-text-muted)">
          {data ? `${formatNumber(data.total)} alerts` : "Loading…"} — operational alert management center (SIMULATION MODE: alerts are generated by the simulation engine and seed scenarios).
        </p>
      </div>

      <Card className="p-3">
        <div className="flex flex-wrap items-center gap-2">
          <select
            value={severity}
            onChange={(e) => updateFilter("severity", e.target.value)}
            className="rounded-lg border bg-(--app-surface) px-3 py-1.5 text-sm text-(--app-text)"
            style={{ borderColor: "var(--app-border)" }}
          >
            <option value="">All severities</option>
            {SEVERITIES.map((s) => <option key={s} value={s}>{prettyStatus(s)}</option>)}
          </select>
          <select
            value={status}
            onChange={(e) => updateFilter("status", e.target.value)}
            className="rounded-lg border bg-(--app-surface) px-3 py-1.5 text-sm text-(--app-text)"
            style={{ borderColor: "var(--app-border)" }}
          >
            <option value="">All statuses</option>
            {STATUSES.map((s) => <option key={s} value={s}>{prettyStatus(s)}</option>)}
          </select>
        </div>
      </Card>

      {error && <Card className="border-status-red p-3 text-sm text-status-red">{error}</Card>}

      <Card className="overflow-hidden p-0">
        {loading ? (
          <div className="flex items-center justify-center gap-2 py-16 text-(--app-text-muted)">
            <Loader2 className="h-4 w-4 animate-spin" /> Loading alerts…
          </div>
        ) : (
          <table className="w-full text-sm">
            <thead>
              <tr className="border-b text-left text-xs uppercase tracking-wide text-(--app-text-muted)" style={{ borderColor: "var(--app-border)" }}>
                <th className="px-4 py-2.5 font-medium">Severity</th>
                <th className="px-4 py-2.5 font-medium">Alert</th>
                <th className="px-4 py-2.5 font-medium">Source</th>
                <th className="px-4 py-2.5 font-medium">Related</th>
                <th className="px-4 py-2.5 font-medium">Status</th>
                <th className="px-4 py-2.5 font-medium">Created</th>
                <th className="px-4 py-2.5 font-medium">Actions</th>
              </tr>
            </thead>
            <tbody>
              {data?.items.map((a) => (
                <tr key={a.id} className="border-b last:border-0 align-top" style={{ borderColor: "var(--app-border)" }}>
                  <td className="px-4 py-2.5"><StatusBadge tone={statusTone(a.severity)} label={prettyStatus(a.severity)} /></td>
                  <td className="px-4 py-2.5 max-w-xs">
                    <p className="font-medium text-(--app-text)">{a.title}</p>
                    <p className="text-xs text-(--app-text-muted)">{a.description}</p>
                    {a.recommended_action && <p className="mt-1 text-xs italic text-(--app-text-muted)">{a.recommended_action}</p>}
                  </td>
                  <td className="px-4 py-2.5 text-(--app-text-muted)">{a.source}</td>
                  <td className="px-4 py-2.5 text-(--app-text-muted)">
                    {a.related_order_id && (
                      <button className="text-teal-600 hover:underline" onClick={() => navigate(`/orders/${a.related_order_id}`)}>
                        {a.related_order_number}
                      </button>
                    )}
                    {a.related_station_id && !a.related_order_id && (
                      <button className="text-teal-600 hover:underline" onClick={() => navigate(`/stations/${a.related_station_id}`)}>
                        {a.related_station_name}
                      </button>
                    )}
                    {a.related_tanker_id && (
                      <button className="text-teal-600 hover:underline" onClick={() => navigate(`/fleet/${a.related_tanker_id}`)}>
                        {a.related_tanker_code}
                      </button>
                    )}
                    {a.related_driver_id && !a.related_tanker_id && (
                      <button className="text-teal-600 hover:underline" onClick={() => navigate("/drivers")}>
                        {a.related_driver_name}
                      </button>
                    )}
                    {!a.related_order_id && !a.related_station_id && !a.related_driver_id && !a.related_tanker_id && "—"}
                  </td>
                  <td className="px-4 py-2.5"><StatusBadge tone={statusTone(a.status)} label={prettyStatus(a.status)} /></td>
                  <td className="px-4 py-2.5 text-(--app-text-muted)">{formatDateTime(a.created_at)}</td>
                  <td className="px-4 py-2.5">
                    <div className="flex flex-wrap gap-1.5">
                      {a.status === "open" && (
                        <Button variant="secondary" loading={busyId === a.id} onClick={() => runAction(a.id, "acknowledge")}>
                          <Check className="h-3.5 w-3.5" /> Ack
                        </Button>
                      )}
                      {a.status !== "resolved" && (
                        <Button variant="secondary" loading={busyId === a.id} onClick={() => runAction(a.id, "resolve")}>
                          <CheckCheck className="h-3.5 w-3.5" /> Resolve
                        </Button>
                      )}
                      {a.status !== "resolved" && a.status !== "escalated" && (
                        <Button variant="destructive" loading={busyId === a.id} onClick={() => runAction(a.id, "escalate")}>
                          <ArrowUpCircle className="h-3.5 w-3.5" /> Escalate
                        </Button>
                      )}
                    </div>
                  </td>
                </tr>
              ))}
              {data?.items.length === 0 && (
                <tr><td colSpan={7} className="px-4 py-10 text-center text-(--app-text-muted)">No alerts match these filters.</td></tr>
              )}
            </tbody>
          </table>
        )}
      </Card>
    </div>
  )
}
