import { useMemo } from "react"
import { useNavigate } from "react-router-dom"
import { Video, Gauge, ShieldAlert, Activity, Siren, AlertTriangle, Info, Zap } from "lucide-react"
import { useLiveSnapshot } from "@/lib/useLiveSnapshot"
import { KpiCard } from "@/components/ui/KpiCard"
import { Card, CardHeader, CardTitle, CardContent } from "@/components/ui/Card"
import { StatusBadge } from "@/components/ui/Badge"
import { statusTone, prettyStatus } from "@/lib/orderStatus"
import { formatNumber, formatTime } from "@/lib/utils"

const EVENT_ICON = { info: Info, warning: AlertTriangle, critical: Siren } as const

export function Ivms() {
  const navigate = useNavigate()
  const { snapshot, connected } = useLiveSnapshot()

  const vehicles = snapshot?.ivms_vehicles ?? []
  const events = snapshot?.ivms_events ?? []

  const summary = useMemo(() => {
    const driving = vehicles.filter((v) => v.engine_status === "running")
    const avgScore = vehicles.length ? vehicles.reduce((sum, v) => sum + v.driving_score, 0) / vehicles.length : 0
    const alertCount = vehicles.filter((v) => v.fatigue_level === "alert").length
    const unbelted = driving.filter((v) => !v.seatbelt_fastened).length
    return { drivingCount: driving.length, avgScore, alertCount, unbelted }
  }, [vehicles])

  return (
    <div className="space-y-4">
      <p className="text-sm text-(--app-text-muted)">
        IVMS — In-Vehicle Monitoring System — SIMULATION MODE. Per-tanker driver-behavior telemetry (speed, harsh
        braking/acceleration, seatbelt status, fatigue indicators and a running driving score) is synthetic,
        generated by the simulation engine; this page is never connected to a real IVMS device, dash-cam or
        telematics unit.
      </p>

      {!snapshot ? (
        <Card className="p-8 text-center text-sm text-(--app-text-muted)">
          {connected ? "Connecting…" : "Connecting to the simulation engine…"}
        </Card>
      ) : (
        <>
          <div className="grid grid-cols-2 gap-4 md:grid-cols-4">
            <KpiCard label="Fleet Size" value={formatNumber(vehicles.length)} icon={Video} tone="blue" />
            <KpiCard label="Driving Now" value={formatNumber(summary.drivingCount)} icon={Gauge} tone="teal" />
            <KpiCard label="Avg. Driving Score" value={summary.avgScore.toFixed(0)} icon={Activity} tone={summary.avgScore < 85 ? "amber" : "green"} />
            <KpiCard
              label="Fatigue Alerts"
              value={formatNumber(summary.alertCount)}
              icon={ShieldAlert}
              tone={summary.alertCount > 0 ? "red" : "green"}
              sublabel={summary.unbelted > 0 ? `${summary.unbelted} seatbelt violation(s) in progress` : undefined}
            />
          </div>

          <Card className="overflow-hidden p-0">
            <CardHeader><CardTitle>Fleet Driver-Behavior Monitor</CardTitle></CardHeader>
            <CardContent className="p-0">
              <table className="w-full text-sm">
                <thead>
                  <tr className="border-b text-left text-xs uppercase tracking-wide text-(--app-text-muted)" style={{ borderColor: "var(--app-border)" }}>
                    <th className="px-4 py-2.5 font-medium">Tanker</th>
                    <th className="px-4 py-2.5 font-medium">Driver</th>
                    <th className="px-4 py-2.5 font-medium">Engine</th>
                    <th className="px-4 py-2.5 font-medium">Speed</th>
                    <th className="px-4 py-2.5 font-medium">Seatbelt</th>
                    <th className="px-4 py-2.5 font-medium">Driving Score</th>
                    <th className="px-4 py-2.5 font-medium">Harsh Events</th>
                    <th className="px-4 py-2.5 font-medium">Fatigue</th>
                  </tr>
                </thead>
                <tbody>
                  {vehicles.map((v) => (
                    <tr
                      key={v.tanker_id}
                      className="cursor-pointer border-b last:border-0 transition hover:bg-black/[0.02]"
                      style={{ borderColor: "var(--app-border)" }}
                      onClick={() => navigate(`/fleet/${v.tanker_id}`)}
                    >
                      <td className="px-4 py-2.5 font-medium text-(--app-text)">{v.tanker_code}</td>
                      <td className="px-4 py-2.5 text-(--app-text-muted)">{v.driver_name ?? "—"}</td>
                      <td className="px-4 py-2.5"><StatusBadge tone={statusTone(v.engine_status)} label={prettyStatus(v.engine_status)} /></td>
                      <td className="px-4 py-2.5 tabular-nums text-(--app-text)">
                        {v.engine_status === "running" ? (
                          <span className="flex items-center gap-1">
                            {v.speed_kmh > 100 && <Zap className="h-3.5 w-3.5 text-status-red" />}
                            {v.speed_kmh.toFixed(0)} km/h
                          </span>
                        ) : (
                          "—"
                        )}
                      </td>
                      <td className="px-4 py-2.5">
                        {v.engine_status === "running" ? (
                          <StatusBadge tone={v.seatbelt_fastened ? "green" : "red"} label={v.seatbelt_fastened ? "Fastened" : "Unfastened"} />
                        ) : (
                          <span className="text-(--app-text-muted)">—</span>
                        )}
                      </td>
                      <td className="px-4 py-2.5">
                        <div className="flex items-center gap-2">
                          <div className="h-1.5 w-20 overflow-hidden rounded-full bg-black/5">
                            <div
                              className={`h-full rounded-full ${v.driving_score < 70 ? "bg-status-red" : v.driving_score < 85 ? "bg-status-amber" : "bg-status-green"}`}
                              style={{ width: `${v.driving_score}%` }}
                            />
                          </div>
                          <span className="tabular-nums text-(--app-text)">{v.driving_score.toFixed(0)}</span>
                        </div>
                      </td>
                      <td className="px-4 py-2.5 tabular-nums text-(--app-text-muted)">{v.harsh_events_session}</td>
                      <td className="px-4 py-2.5"><StatusBadge tone={statusTone(v.fatigue_level)} label={prettyStatus(v.fatigue_level)} /></td>
                    </tr>
                  ))}
                  {vehicles.length === 0 && (
                    <tr><td colSpan={8} className="px-4 py-10 text-center text-(--app-text-muted)">No IVMS telemetry yet.</td></tr>
                  )}
                </tbody>
              </table>
            </CardContent>
          </Card>

          <Card>
            <CardHeader>
              <CardTitle>Driver-Behavior Event Log</CardTitle>
              <span className="text-xs text-(--app-text-muted)">Harsh braking/acceleration, overspeeding, seatbelt and fatigue events</span>
            </CardHeader>
            <CardContent className="space-y-2">
              {events.length === 0 ? (
                <p className="py-4 text-center text-sm text-(--app-text-muted)">No driver-behavior events logged yet this session.</p>
              ) : (
                [...events].reverse().map((e) => {
                  const Icon = EVENT_ICON[e.severity]
                  const tone = e.severity === "critical" ? "text-status-red bg-status-red-bg" : e.severity === "warning" ? "text-status-amber bg-status-amber-bg" : "text-status-blue bg-status-blue-bg"
                  return (
                    <div key={e.id} className="flex items-start justify-between gap-3 rounded-lg border px-3 py-2 text-sm" style={{ borderColor: "var(--app-border)" }}>
                      <div className="flex items-start gap-2.5">
                        <span className={`mt-0.5 shrink-0 rounded-md p-1.5 ${tone}`}>
                          <Icon className="h-3.5 w-3.5" />
                        </span>
                        <span className="text-(--app-text)">
                          <span className="font-medium">{e.tanker_code}</span>
                          {e.driver_name && <span className="text-(--app-text-muted)"> · {e.driver_name}</span>} — {e.message}
                        </span>
                      </div>
                      <span className="shrink-0 text-xs text-(--app-text-muted)">{formatTime(e.timestamp)}</span>
                    </div>
                  )
                })
              )}
            </CardContent>
          </Card>
        </>
      )}
    </div>
  )
}
